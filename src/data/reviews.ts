/** Real published reviews — empty until authentic submissions exist. */
export const PUBLISHED_REVIEWS: ReviewRecord[] = [];

function localizeReview(r: ReviewRecord, locale: ReviewLocale): ReviewRecord {
  return {
    ...r,
    author: locale === "ar" ? r.authorAr : r.authorFr,
    text: locale === "ar" ? r.textAr : r.textFr,
  };
}

export function eligibleReviews(opts?: {
  productSlug?: string;
  fit?: "baggy" | "straight";
  includeDemo?: boolean;
  locale?: ReviewLocale;
}): ReviewRecord[] {
  const locale: ReviewLocale = opts?.locale === "ar" ? "ar" : "fr";
  const allowDemo =
    Boolean(opts?.includeDemo) && process.env.NODE_ENV !== "production";
  const pool = [
    ...PUBLISHED_REVIEWS.filter((r) => r.publish && !r.isDemo),
    ...(allowDemo ? DEMO_REVIEWS : []),
  ];
  return pool
    .filter((r) => {
      if (opts?.productSlug && r.productSlug && r.productSlug !== opts.productSlug) {
        return false;
      }
      if (opts?.fit && r.fit && r.fit !== opts.fit) return false;
      return true;
    })
    .map((r) => localizeReview(r, locale));
}

